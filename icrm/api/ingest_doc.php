--- Постановка задачи агенту (изнутри системы, например после ошибки) ---
POST {$base}/api/task_queue.php
X-Ingest-Key: <ключ>
Content-Type: application/json

{
  "project_ref": "WINTASK",        // либо "chat_id": -1004434028499
  "title": "Почини конвейер заявок: с 12:10 падает cron выгрузки",
  "prio": 2,                       // 1 — деньги (по умолчанию 2)
  "parent_id": 28,                 // необязательно: подпроект вместо корня направления
  "source": "watcher",             // от кого пришла задача
  "note": "ошибка в логе",         // необязательно
  "dry_run": false                 // true — только проверить, не создавая
}

Ответ: {"ok":true,"task_id":42,"dup":false,"project_ref":"WINTASK","title":"..."}

Как это работает:
  • задача попадает в план (как обычная задача в дереве) и её забирает сторож;
  • агент получает ТОЛЬКО текст задачи — без ID, протокола и служебных строк;
  • "dup":true — такая же незакрытая задача уже есть, новую не создавали;
  • от одного источника (source) в направлении не больше 3 открытых задач —
    защита от бесконечного потока при повторяющейся ошибке.

