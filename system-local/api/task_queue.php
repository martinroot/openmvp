<?php
declare(strict_types=1);
/**
 * Постановка задачи агенту изнутри системы — на фикс после ошибки.
 *
 * POST /api/task_queue.php
 *   заголовок: X-Ingest-Key: <ключ>
 *   тело (JSON):
 *     {
 *       "project_ref": "WINTASK",      // либо "chat_id": -1004434028499
 *       "title": "Почини конвейер заявок: с 12:10 падает cron выгрузки",
 *       "prio": 2,                     // 1 — деньги (по умолчанию 2)
 *       "parent_id": 28,               // необязательно: подпроект вместо корня направления
 *       "source": "watcher",           // от кого пришла задача
 *       "note": "ошибка в логе",       // необязательно
 *       "dry_run": false               // true — только проверить, не создавая
 *     }
 *
 * Ответ: {"ok":true,"task_id":42,"dup":false,"project_ref":"WINTASK","title":"..."}
 *   dup=true — такая же незакрытая задача уже есть, новую не создавали.
 *
 * Задача попадает в план (дерево), её забирает сторож и отдаёт агенту.
 * Агент видит только текст задачи.
 */
require __DIR__ . '/../lib/ingest.php';
require __DIR__ . '/../lib/queue.php';

// Ключ не обязателен: с сервера агента (IP из карточек проектов) запрос
// принимается и без него — агенту не нужно ничего настраивать.
// С чужого адреса — только по ключу.
if (!ingest_key_ok() && !ingest_trusted_ip()) {
    ingest_check_key();          // вернёт 401 и выйдет
}

$b     = ingest_body();
$res   = queue_task($b);
$code  = (int)($res['code'] ?? 200);
unset($res['code']);
ingest_json($res, $code >= 200 && $code < 300 ? 200 : $code);
